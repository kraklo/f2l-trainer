// Gyro quaternions. The library's frame is right-handed with +X red, +Y blue, +Z white, and a
// quaternion maps the cube body into the world, so conj(ref) ⊗ q is the body-frame rotation since ref.
//
// There is no fixed calibration: the grip is tilted and the world reference drifts between sessions.
// Instead the reference grip is the dominant orientation while scrambling, which is white top,
// green front by construction.

import { type GyroSample, type Quat } from '../record/types';

export function qmul(a: Quat, b: Quat): Quat {
  const [ax, ay, az, aw] = a, [bx, by, bz, bw] = b;
  return [
    aw * bx + ax * bw + ay * bz - az * by,
    aw * by - ax * bz + ay * bw + az * bx,
    aw * bz + ax * by - ay * bx + az * bw,
    aw * bw - ax * bx - ay * by - az * bz,
  ];
}

export function qconj([x, y, z, w]: Quat): Quat {
  return [-x, -y, -z, w];
}

function qnormalize(q: Quat): Quat {
  const n = Math.hypot(...q);
  return [q[0] / n, q[1] / n, q[2] / n, q[3] / n];
}

function qdot(a: Quat, b: Quat): number {
  return a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3];
}

/** Angle in degrees of the rotation taking a to b. */
export function angleBetween(a: Quat, b: Quat): number {
  return (2 * Math.acos(Math.min(1, Math.abs(qdot(a, b)))) * 180) / Math.PI;
}

/** Body-frame rotation from `ref` to `q`. */
export function relative(ref: Quat, q: Quat): Quat {
  return qmul(qconj(ref), q);
}

function axisAngle(axis: [number, number, number], deg: number): Quat {
  const h = (deg * Math.PI) / 360;
  return [axis[0] * Math.sin(h), axis[1] * Math.sin(h), axis[2] * Math.sin(h), Math.cos(h)];
}

/** The 24 whole-cube orientations, generated by quarter turns about the three axes; [0] is identity. */
export const ORIENTATIONS: Quat[] = (() => {
  const gens = [axisAngle([1, 0, 0], 90), axisAngle([0, 1, 0], 90), axisAngle([0, 0, 1], 90)];
  const out: Quat[] = [[0, 0, 0, 1]];
  for (let i = 0; i < out.length; i++) {
    for (const g of gens) {
      const q = qnormalize(qmul(out[i], g));
      if (!out.some((o) => Math.abs(qdot(o, q)) > 0.999)) out.push(q);
    }
  }
  return out;
})();

/** Nearest of the 24 orientations to a body-frame rotation, and how far off it is in degrees. */
export function snap(rel: Quat): { index: number; angle: number } {
  let index = 0, best = -1;
  ORIENTATIONS.forEach((o, i) => {
    const d = Math.abs(qdot(o, rel));
    if (d > best) {
      best = d;
      index = i;
    }
  });
  return { index, angle: (2 * Math.acos(Math.min(1, best)) * 180) / Math.PI };
}

const CLUSTER_DEG = 25;

/**
 * The dominant orientation among `samples`: the largest group within 25° of one sample, averaged.
 * Used on scramble samples, where the user mostly holds white top, green front but tumbles the cube.
 */
export function referenceGrip(samples: GyroSample[]): Quat | null {
  if (!samples.length) return null;
  const qs = samples.map((s) => s.q);
  let centre = qs[0], count = 0;
  for (const a of qs) {
    const c = qs.filter((b) => angleBetween(a, b) <= CLUSTER_DEG).length;
    if (c > count) {
      count = c;
      centre = a;
    }
  }
  const sum: Quat = [0, 0, 0, 0];
  for (const q of qs) {
    if (angleBetween(centre, q) > CLUSTER_DEG) continue;
    const s = qdot(centre, q) < 0 ? -1 : 1;
    for (let i = 0; i < 4; i++) sum[i] += s * q[i];
  }
  return qnormalize(sum);
}
